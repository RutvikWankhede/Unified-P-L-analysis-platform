import csv
import io
import logging
from typing import Any, Dict, List
from fpdf import FPDF

logger = logging.getLogger(__name__)


class EnterprisePDF(FPDF):
    def header(self):
        # Draw premium top header
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(161, 161, 170)  # tailwind slate-400
        self.cell(
            0,
            5,
            "UNIFIED P&L FINANCIAL INTELLIGENCE PLATFORM",
            new_x="LMARGIN",
            new_y="NEXT",
            align="L",
        )

        # Horizontal rule
        self.set_draw_color(39, 39, 42)  # border gray
        self.set_line_width(0.4)
        self.line(10, 15, 200, 15)
        self.ln(5)

    def footer(self):
        # Draw footer horizontal rule
        self.set_draw_color(39, 39, 42)
        self.set_line_width(0.4)
        self.line(10, 282, 200, 282)

        # Position at 1.5 cm from bottom
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(161, 161, 170)
        self.cell(0, 10, "CONFIDENTIAL - SYSTEM GENERATED FINANCIAL INTEL", align="L")

        # Page number
        self.set_y(-15)
        self.cell(0, 10, f"Page {self.page_no()}", align="R")


class ReportService:
    """
    Generates PDF, CSV, Excel, and Interactive HTML reports.
    """

    def generate_csv_report(self, data: List[Dict[str, Any]]) -> io.StringIO:
        logger.info("Generating CSV Report")
        output = io.StringIO()
        if not data:
            return output

        writer = csv.DictWriter(output, fieldnames=data[0].keys())
        writer.writeheader()
        writer.writerows(data)
        output.seek(0)
        return output

